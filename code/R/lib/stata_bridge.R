# Bridge between the single configuration source (config/config.yml) and Stata.
# Stata cannot read YAML, so the parameters it needs are written to config/stata_params.do.

welcom_version <- function(cfg) {
  f <- p_root(cfg, cfg$paths$stata_ado, "_", "_welcom_vers.ado")
  if (!file.exists(f)) return(list(version = NA_character_, date = NA_character_))
  x <- readLines(f, warn = FALSE)
  pick <- function(key) {
    l <- x[grepl(paste0("^\\s*local\\s+", key), x)][1]
    gsub("\"", "", trimws(sub(paste0("^\\s*local\\s+", key, "\\s+"), "", l)))
  }
  list(version = pick("inst_ver"), date = pick("inst_dat"))
}

write_stata_params <- function(cfg) {
  wv <- welcom_version(cfg)
  e <- cfg$estimation
  lines <- c(
    "* Generated by code/R/lib/stata_bridge.R from config/config.yml. Do not edit by hand.",
    sprintf("global SEED_BOOT %d", as.integer(cfg$seeds$stata_bootstrap)),
    sprintf("global SEED_WELCOM_NATIVE %d", as.integer(cfg$seeds$stata_welcom_native)),
    sprintf("global BOOT_FINAL %d", as.integer(e$boot_reps_final)),
    sprintf("global BOOT_FIRST_PASS %d", as.integer(e$boot_reps_first_pass)),
    sprintf("global BOOT_SENS %d", as.integer(e$boot_reps_sensitivity)),
    sprintf("global SCRATCH_DIR \"%s\"", if (is.null(cfg$local$stata_scratch_dir)) "" else gsub("\\\\", "/", cfg$local$stata_scratch_dir)),
    sprintf("global WELCOM_NATIVE_BOOT %d", as.integer(e$welcom_native_boot)),
    sprintf("global CI_LEVEL %s", format(e$ci_level)),
    sprintf("global STATA_PROCESSORS %d", as.integer(e$stata_processors_per_worker)),
    sprintf("global WELCOM_VERSION \"%s (%s)\"", wv$version, wv$date))
  writeLines(lines, p_root(cfg, "config", "stata_params.do"))
  invisible(lines)
}
